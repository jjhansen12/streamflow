import matplotlib.pyplot as plt
import numpy as np

"""### Part 1a - Shear Diagram

You will create your shear diagram in the code block below.

"""

# Define beam variables and external forces
L = 6
R_A = 170
R_B = 410
P_1 = 100
q_1 = 120
q_2 = 120

# Define x using np.linspace
x = np.linspace(0, L, 500)

# Define v using np.zeros_like with x as argument
V = np.zeros_like(x) # creates a new list filled entirely with zeros, and it makes sure that the new list is the exact same size and shape as the old one.

# Use a for loop to define the piecewise function for shear force V
for i in range(len(x)):
    val = x[i] # ai helped me learn that val = x[i] just grabs the exact number stored at that current spot and saves it into a temporary variable called val so that we can do math on it
    if val < 2:
        V[i] = R_A - (q_1 * val)
    elif val > 4:
        V[i] = R_A - (q_1 * 2) - P_1 + R_B - (q_2 * (val - 4))
    else:
        V[i] = R_A - (q_1 * 2) - P_1

# Plot x against V, fill the area, and add standard formatting
plt.plot(x, V, color='cornflowerblue', linewidth=2)
plt.fill_between(x, V, color='cornflowerblue', alpha=0.3)
plt.axhline(0, color='black', linewidth=1)
plt.title('Shear Diagram')
plt.xlabel('x (ft)')
plt.ylabel('V (lb)')
plt.grid(True)
plt.show()

"""### Part 1b - Moment Diagram

You will create your moment diagram in the code block below.
"""

# Copy and paste variables from Part 1a
L = 6
R_A = 170
R_B = 410
P_1 = 100
q_1 = 120
q_2 = 120

# Define x using np.linspace
x = np.linspace(0, L, 500)

# Define M using np.zeros_like with x as the argument
M = np.zeros_like(x)

# Use a for loop to define the piecewise function for bending moment M
for i in range(len(x)):
    val = x[i] # ai helped me learn that val = x[i] just grabs the exact number stored at that current spot and saves it into a temporary variable called val so that we can do math on it
    if val < 2:
        M[i] = (R_A * val) - (q_1 * (val**2) / 2)
    elif val > 4:
        M[i] = (R_A * val) - (q_1 * 2 * (val - 1)) - (P_1 * (val - 2)) + (R_B * (val - 4)) - (q_2 * (val - 4) * ((val - 4) / 2))
    else:
        M[i] = (R_A * val) - (q_1 * 2 * (val - 1)) - (P_1 * (val - 2))

# Plot x against M, fill the area, and add standard formatting
plt.plot(x, M, color='cornflowerblue', linewidth=2)
plt.fill_between(x, M, color='cornflowerblue', alpha=0.3)
plt.axhline(0, color='black', linewidth=1)
plt.title('Moment Diagram')
plt.xlabel('x (ft)')
plt.ylabel('M (lb-ft)')
plt.grid(True)
plt.show()

